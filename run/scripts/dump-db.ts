/**
 * dump-db.ts — full data backup of the nextapp Postgres DB.
 *
 * Output format matches the historical db/medq-backup-*.sql dumps exactly:
 *   BEGIN; SET session_replication_role = replica;   -- bypass FK triggers
 *   INSERT INTO "Table" SELECT * FROM json_populate_record(NULL::"Table", $tag${...json...}$tag$);
 *   ... per table, in reverse-FK-safe order (replica mode makes order moot) ...
 *   SET session_replication_role = DEFAULT; COMMIT;
 *
 * Restore with scripts/restore-db-latest.mjs (or psql -f) AFTER `prisma db push`.
 *
 * Usage: bun scripts/dump-db.ts [db/medq-backup-YYYYMMDD.sql]
 *
 * MEMORY (2026-10-24): the original version accumulated every table's rows
 * AND all INSERT lines in a single `lines: string[]` before one Bun.write —
 * ~210MB of SQL = 1.5-2GB of JS heap alongside the prod server → kernel
 * OOM-kill (silent, exit 137) on the 4GB box. This version STREAMS: a
 * Bun FileSink receives per-row INSERTs as they are stringified, and each
 * table is fetched in LIMIT/OFFSET pages, so peak memory stays at ~one page
 * (~100 rows) regardless of database size. Output format is unchanged.
 */
import { SQL } from 'bun';

const PAGE = 100; // rows per fetch page — peak-memory knob

const OUT = process.argv[2] || `db/medq-backup-${new Date().toISOString().slice(0, 10).replace(/-/g, '')}.sql`;
const CONN = 'postgresql://postgres:postgres@127.0.0.1:5432/nextapp';

// Random dollar-quote tag that cannot collide with row data.
const tag = `$medq${Math.random().toString(36).slice(2, 10)}$`;

const sql = new SQL(CONN);

// Every base table in public, largest-first so the restore log is readable.
// session_replication_role=replica means insert order is irrelevant for FKs.
const tables: { table_name: string }[] = await sql`
  SELECT table_name FROM information_schema.tables
  WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
  ORDER BY table_name
`;

// Streaming writer — rows hit disk as they are produced, never accumulate.
const sink = Bun.file(OUT).writer({ highWaterMark: 1 << 20 });
await sink.write(
  '-- MedQ full data backup (generated by scripts/dump-db.ts)\n' +
  '-- Restore into a schema-created DB (prisma db push) then:\n' +
  '--   psql "$DATABASE_URL" -f this-file.sql\n' +
  'BEGIN;\n' +
  'SET session_replication_role = replica; -- bypass FK triggers during restore\n\n',
);

let totalRows = 0;
for (const { table_name: t } of tables) {
  // Row count first (matches the historical `-- Table: N rows` placement
  // BEFORE the block's INSERTs), then page through the rows.
  const [{ n }] = await sql`SELECT COUNT(*)::int AS n FROM ${sql(t)}`;
  await sink.write(`-- ${t}: ${n} rows\n`);
  let tableRows = 0;
  let offset = 0;
  for (;;) {
    const rows: Record<string, unknown>[] = await sql`SELECT * FROM ${sql(t)} LIMIT ${PAGE} OFFSET ${offset}`;
    if (rows.length === 0) break;
    offset += rows.length;
    tableRows += rows.length;
    for (const r of rows) {
      // JSON stringify: Date/BigInt become ISO strings/numbers; NULL stays null;
      // json_populate_record coerces each JSON value to the column type.
      // Dollar-quoting does NO backslash processing, so JSON.stringify's own
      // escaping is exactly what should land in the file — no re-escaping.
      const json = JSON.stringify(r);
      await sink.write(`INSERT INTO "${t}" SELECT * FROM json_populate_record(NULL::"${t}", ${tag}${json}${tag});\n`);
    }
  }
  if (tableRows !== n) throw new Error(`${t}: count(${n}) != paged(${tableRows}) — dump aborted, file incomplete`);
  totalRows += tableRows;
  await sink.write('\n');
  await sink.flush();
}

await sink.write(
  '-- Reset sequences\n' +
  'SET session_replication_role = DEFAULT;\n' +
  'COMMIT;\n',
);
await sink.end();
await sql.end();

console.log(`wrote ${OUT}: ${tables.length} tables, ${totalRows} rows (streamed, pages of ${PAGE})`);
